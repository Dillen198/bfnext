//! Finding DCS profiles and putting the cockpit plugin in them.
//!
//! The plugin is client-side: a Lua file in a DCS profile's `Scripts\Hooks`
//! folder, which is the engine's supported extension point for code that runs
//! on the player's own machine, plus a `Mods\Services\BFCockpit` plugin that
//! gives it a page under Options -> Special (the show/hide key, panel size)
//! and carries `bin\bfcockpit_net.dll`, which gives the script HTTPS (DCS's
//! Lua has none). Installing it by hand is
//! three steps and two folders that often don't exist yet, and players
//! routinely have several DCS profiles -- stable and Open Beta, a server
//! profile, a `--write-dir` profile for VR settings. Putting the script in one
//! of them and then wondering why it didn't load is the failure this exists to
//! prevent, so it finds every profile and does all of them.
//!
//! Both files are embedded here (the DLL by build.rs), so the installer is a
//! single file with nothing to unzip and nothing to keep beside it.
//!
//! Nothing outside a DCS profile is touched: no DCS install files, no registry
//! writes, nothing added to startup. In particular it does NOT touch
//! `DCS World\Scripts\MissionScripting.lua` -- that sanitizes the *mission
//! scripting* state, which is a server-side concern and has no bearing on a
//! Hooks script running on a client.
//!
//! Both front ends (the window and the command line) sit on top of this.
use anyhow::{Context, Result};
use std::{
    collections::BTreeSet,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

/// The plugin itself, baked in.
pub const HOOK_LUA: &str = include_str!("../../Scripts/Hooks/bfcockpit.lua");
pub const HOOK_NAME: &str = "bfcockpit.lua";
/// The HTTPS helper the script loads, embedded by build.rs. Empty when the
/// installer was built before the DLL was (see build.rs); `install_one`
/// refuses then rather than install a plugin that cannot reach the server.
pub const NET_DLL: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/bfcockpit_net.dll"));
pub const NET_DLL_NAME: &str = "bfcockpit_net.dll";
/// The plugin folder, relative to the profile: DCS lists it under Options ->
/// Special, and the DLL lives in its `bin`.
pub const PLUGIN_DIR: [&str; 3] = ["Mods", "Services", "BFCockpit"];
/// Where 2.0 put the DLL (`Scripts\BFCockpit`). Removed on install.
pub const LEGACY_NET_DIR: [&str; 2] = ["Scripts", "BFCockpit"];

/// Every file of the plugin folder (Mods/Services/BFCockpit: entry.lua, the
/// Options page, the Vector Strike icons and the wheel's art), relative to
/// PLUGIN_DIR. Generated by build.rs from the folder, so a new file there is
/// installed without anyone listing it.
pub const PLUGIN_FILES: &[(&str, &[u8])] =
    include!(concat!(env!("OUT_DIR"), "/plugin_files.rs"));

/// The line in options.dlg the installer fills in. DCS runs a .dlg with no
/// globals at all, so the page cannot find its own logo; the installer, which
/// knows where it is putting it, writes the absolute path in.
const LOGO_MARKER: &str = "local logoFile = nil -- BFCOCKPIT_LOGO_PATH";

fn join_all(base: &Path, parts: &[&str]) -> PathBuf {
    parts.iter().fold(base.to_path_buf(), |p, s| p.join(s))
}

pub fn plugin_dir(profile: &Path) -> PathBuf {
    join_all(profile, &PLUGIN_DIR)
}

pub fn net_dll_path(profile: &Path) -> PathBuf {
    plugin_dir(profile).join("bin").join(NET_DLL_NAME)
}
pub const DEFAULT_URL: &str = "https://api.vectorstrike.org";

/// The campaign API's origin from whatever the player was given: version 1
/// took the web page's address (".../cockpit"), the plugin now wants the host.
pub fn api_origin(url: &str) -> String {
    let url = url.trim().trim_end_matches('/');
    match url.find("://") {
        Some(i) => match url[i + 3..].find('/') {
            Some(j) => url[..i + 3 + j].to_string(),
            None => url.to_string(),
        },
        None => url.to_string(),
    }
}

/// A DCS profile and what is installed in it.
#[derive(Debug, Clone)]
pub struct Profile {
    pub path: PathBuf,
    /// Version of the overlay already there, if any.
    pub installed: Option<String>,
}

impl Profile {
    pub fn name(&self) -> String {
        self.path
            .file_name()
            .map(|s| s.to_string_lossy().into_owned())
            .unwrap_or_else(|| self.path.display().to_string())
    }

    /// Short status for a list: what is there versus what we ship.
    pub fn status(&self) -> String {
        let has_dll = net_dll_path(&self.path).is_file()
            && plugin_dir(&self.path).join("entry.lua").is_file();
        match &self.installed {
            None => "not installed".into(),
            Some(v) if v == plugin_version() && has_dll => "already up to date".into(),
            Some(v) if v == plugin_version() => {
                format!("{v} installed, plugin files missing")
            }
            Some(v) => format!("{v} installed"),
        }
    }
}

/// What a scan turned up.
#[derive(Debug, Clone, Default)]
pub struct Scan {
    pub profiles: Vec<Profile>,
    /// Folders that look like DCS but have no `Config` -- named so that "it
    /// didn't find my profile" has an answer.
    pub near_misses: Vec<PathBuf>,
    /// Where we looked.
    pub roots: Vec<PathBuf>,
}

/// Find every DCS profile on this machine.
pub fn scan(extra_roots: &[PathBuf]) -> Scan {
    let (paths, near_misses) = discover(extra_roots);
    Scan {
        profiles: paths
            .into_iter()
            .map(|p| Profile { installed: installed_version(&p), path: p })
            .collect(),
        near_misses,
        roots: search_roots(extra_roots),
    }
}

/// Treat these specific folders as profiles, without searching.
pub fn profiles_at(paths: &[PathBuf]) -> (Vec<Profile>, Vec<PathBuf>) {
    let mut found = Vec::new();
    let mut missing = Vec::new();
    for p in paths {
        if p.is_dir() {
            found.push(Profile { installed: installed_version(p), path: p.clone() });
        } else {
            missing.push(p.clone());
        }
    }
    (found, missing)
}

/// Version declared by the embedded script. Single source of truth -- bfdb
/// parses the same line out of the same file.
pub fn plugin_version() -> &'static str {
    HOOK_LUA
        .lines()
        .find_map(|l| {
            let rest = l.trim().strip_prefix("local BFCOCKPIT_VERSION")?;
            let rest = rest.trim_start().strip_prefix('=')?;
            rest.trim().trim_start_matches('"').split('"').next()
        })
        .unwrap_or("unknown")
}

pub fn installed_version(profile: &Path) -> Option<String> {
    let text =
        fs::read_to_string(profile.join("Scripts").join("Hooks").join(HOOK_NAME)).ok()?;
    text.lines().find_map(|l| {
        let rest = l.trim().strip_prefix("local BFCOCKPIT_VERSION")?;
        let rest = rest.trim_start().strip_prefix('=')?;
        Some(rest.trim().trim_start_matches('"').split('"').next()?.to_string())
    })
}

/// Everywhere a DCS profile might live.
///
/// `Saved Games` is a Windows known folder and people really do move it --
/// onto another drive, or into OneDrive, in which case `%USERPROFILE%\Saved
/// Games` is not where it is. The authoritative answer is the shell's own
/// record of it, read here from the registry rather than by taking a
/// dependency on the Win32 shell API for one string.
pub fn search_roots(extra: &[PathBuf]) -> Vec<PathBuf> {
    let mut roots: Vec<PathBuf> = Vec::new();
    let mut push = |p: PathBuf| {
        if p.is_dir() && !roots.contains(&p) {
            roots.push(p);
        }
    };

    if let Some(p) = known_saved_games() {
        push(p);
    }
    if let Ok(profile) = std::env::var("USERPROFILE") {
        push(Path::new(&profile).join("Saved Games"));
        push(Path::new(&profile).join("OneDrive").join("Saved Games"));
        push(Path::new(&profile).join("Documents").join("Saved Games"));
    }
    if let Ok(od) = std::env::var("OneDrive") {
        push(Path::new(&od).join("Saved Games"));
    }
    for e in extra {
        push(e.clone());
    }
    roots
}

/// FOLDERID_SavedGames, via the shell's User Shell Folders record.
fn known_saved_games() -> Option<PathBuf> {
    const FOLDERID_SAVED_GAMES: &str = "{4C5C32FF-BB9D-43B0-B5B4-2D72E54EAAA4}";
    let out = Command::new("reg")
        .args([
            "query",
            r"HKCU\Software\Microsoft\Windows\CurrentVersion\Explorer\User Shell Folders",
            "/v",
            FOLDERID_SAVED_GAMES,
        ])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    // One line, three whitespace-separated fields:
    //     {GUID}    REG_SZ           E:\Saved Games
    //     {GUID}    REG_EXPAND_SZ    %USERPROFILE%\Saved Games
    // The value is everything after the type token, and must be taken whole --
    // splitting on whitespace truncates "E:\Saved Games" at the space.
    let text = String::from_utf8_lossy(&out.stdout);
    let line = text.lines().find(|l| l.contains(FOLDERID_SAVED_GAMES))?;
    let type_tok = line.split_whitespace().find(|t| t.starts_with("REG_"))?;
    let after = line.find(type_tok)? + type_tok.len();
    let value = line[after..].trim();
    if value.is_empty() {
        return None;
    }
    Some(PathBuf::from(expand_env(value)))
}

/// Last resort when the registry lookup fails and the usual spots are empty:
/// a relocated `Saved Games` almost always ends up at the root of another
/// drive. Only reached when nothing else turned anything up, so the cost of
/// poking at drive letters is paid once and only when we are otherwise stuck.
fn sweep_drives_for_saved_games() -> Vec<PathBuf> {
    let mut out = Vec::new();
    for letter in b'A'..=b'Z' {
        let p = PathBuf::from(format!("{}:\\Saved Games", letter as char));
        if p.is_dir() {
            out.push(p);
        }
    }
    out
}

/// Expand `%VAR%` the way REG_EXPAND_SZ means it.
fn expand_env(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(start) = rest.find('%') {
        out.push_str(&rest[..start]);
        let after = &rest[start + 1..];
        match after.find('%') {
            Some(end) => {
                let name = &after[..end];
                match std::env::var(name) {
                    Ok(v) => out.push_str(&v),
                    // Not a variable we know -- leave it as written rather
                    // than silently deleting part of the path.
                    Err(_) => {
                        out.push('%');
                        out.push_str(name);
                        out.push('%');
                    }
                }
                rest = &after[end + 1..];
            }
            None => {
                out.push('%');
                out.push_str(after);
                rest = "";
            }
        }
    }
    out.push_str(rest);
    out
}

/// A DCS profile is a `DCS*` folder with a `Config` directory in it. Keying on
/// `Config` rather than on the exact name finds `DCS`, `DCS.openbeta`,
/// `DCS.server`, `DCS.vectorstrike_1` and whatever else someone has made,
/// without mistaking an unrelated Saved Games entry for one.
///
/// Requiring `Config` matters: a Saved Games folder is full of `DCS*` entries
/// that are not profiles at all -- `DCS_F14`, `DCS_F4E`, `DCS.C130J` and
/// friends are per-module data folders written by third-party aircraft, and
/// `DCS MODS` is a mod manager's. Installing a Hooks script into any of them
/// would do nothing at all, silently.
fn discover(extra_roots: &[PathBuf]) -> (Vec<PathBuf>, Vec<PathBuf>) {
    let mut found: BTreeSet<PathBuf> = BTreeSet::new();
    let mut near_misses: BTreeSet<PathBuf> = BTreeSet::new();

    let mut roots = search_roots(extra_roots);
    let scan = |roots: &[PathBuf],
                found: &mut BTreeSet<PathBuf>,
                misses: &mut BTreeSet<PathBuf>| {
        for root in roots {
            let Ok(entries) = fs::read_dir(root) else { continue };
            for e in entries.flatten() {
                let path = e.path();
                if !path.is_dir() {
                    continue;
                }
                let name = e.file_name().to_string_lossy().into_owned();
                if !name.starts_with("DCS") {
                    continue;
                }
                if path.join("Config").is_dir() {
                    found.insert(path);
                } else if path.join("Scripts").is_dir() || path.join("Logs").is_dir() {
                    // Looks profile-ish but has no Config -- usually a folder a
                    // mod manager left behind. Worth naming so "it didn't find
                    // my profile" has an answer.
                    misses.insert(path);
                }
            }
        }
    };

    scan(&roots, &mut found, &mut near_misses);

    if found.is_empty() {
        let swept = sweep_drives_for_saved_games();
        if !swept.is_empty() {
            roots.extend(swept);
            scan(&roots, &mut found, &mut near_misses);
        }
    }

    (found.into_iter().collect(), near_misses.into_iter().collect())
}

pub fn install_one(profile: &Path, url: &str) -> Result<Option<String>> {
    if NET_DLL.is_empty() {
        anyhow::bail!(
            "this installer was built without {NET_DLL_NAME} -- rebuild it after \
             `cargo build --release -p bfcockpit-net`"
        );
    }
    let hooks = profile.join("Scripts").join("Hooks");
    fs::create_dir_all(&hooks)
        .with_context(|| format!("creating {}", hooks.display()))?;

    // The DLL first: while DCS is running it is loaded and locked, and failing
    // here leaves the old script with the old DLL rather than a new script
    // beside a DLL it does not match.
    let dll = net_dll_path(profile);
    if let Some(dir) = dll.parent() {
        fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    }
    if fs::read(&dll).map(|b| b != NET_DLL).unwrap_or(true) {
        fs::write(&dll, NET_DLL).with_context(|| {
            format!("writing {} -- is DCS running? Close it and try again", dll.display())
        })?;
    }

    // The Options -> Special page.
    let plugin = plugin_dir(profile);
    // A fresh copy of the art each time: a file dropped from the plugin must
    // not linger, and a stale wheel layout would place the new art wrongly.
    let wheel_art = plugin.join("Theme").join("wheel");
    if wheel_art.is_dir() {
        let _ = fs::remove_dir_all(&wheel_art);
    }
    let logo = plugin.join("Theme").join("logo.png");
    for (rel, bytes) in PLUGIN_FILES {
        let dest = rel.split('/').fold(plugin.clone(), |p, s| p.join(s));
        if let Some(dir) = dest.parent() {
            fs::create_dir_all(dir)
                .with_context(|| format!("creating {}", dir.display()))?;
        }
        if *rel == "Options/options.dlg" {
            // A Lua long string, so the path's backslashes need no escaping.
            let body = String::from_utf8_lossy(bytes).replace(
                LOGO_MARKER,
                &format!(
                    "local logoFile = [[{}]]",
                    logo.display().to_string().replace('/', "\\")
                ),
            );
            fs::write(&dest, body)
                .with_context(|| format!("writing {}", dest.display()))?;
        } else {
            fs::write(&dest, bytes)
                .with_context(|| format!("writing {}", dest.display()))?;
        }
    }

    // 2.0 kept the DLL in Scripts\BFCockpit. Best effort: if DCS still has
    // that copy loaded it cannot be deleted now, and the new script looks in
    // the new place first anyway.
    let legacy = join_all(profile, &LEGACY_NET_DIR);
    if legacy.is_dir() {
        let _ = fs::remove_dir_all(&legacy);
    }

    let dest = hooks.join(HOOK_NAME);
    let mut note = String::new();
    if dest.is_file() {
        // Keep one backup, so a bad update is recoverable without a download.
        let backup = dest.with_extension("lua.bak");
        fs::copy(&dest, &backup)
            .with_context(|| format!("backing up {}", dest.display()))?;
        note.push_str(" (previous copy kept as bfcockpit.lua.bak)");
    }
    fs::write(&dest, HOOK_LUA).with_context(|| format!("writing {}", dest.display()))?;

    // Seed settings only when there is no file yet: the script writes its own
    // defaults on first run, but doing it here means a player given a
    // non-default server URL never has to edit anything. An existing file --
    // their keys, opacity, window position -- is never touched.
    let cfg = profile.join("Config").join("BFCockpit.lua");
    let api = api_origin(url);
    if !cfg.exists() && api != DEFAULT_URL {
        if let Some(dir) = cfg.parent() {
            fs::create_dir_all(dir).ok();
        }
        let escaped = api.replace('\\', "\\\\").replace('"', "\\\"");
        let body = format!(
            "-- BFNext cockpit plugin settings.\n\
             -- Written by the installer; safe to hand-edit. Every option is\n\
             -- documented in the header of Scripts/Hooks/bfcockpit.lua.\n\
             -- Window position, size and opacity are updated automatically.\n\n\
             cockpit = {{\n    [\"api\"] = \"{escaped}\",\n}}\n"
        );
        if fs::write(&cfg, body).is_ok() {
            note.push_str(" (settings seeded)");
        }
    }

    Ok(Some(format!("installed{note}")))
}

/// `a` is a later version than `b` ("3.10.0" > "3.9.2"). Anything that isn't
/// a number counts as 0, so a garbled version never looks newer.
pub fn is_newer(a: &str, b: &str) -> bool {
    let parts = |v: &str| -> Vec<u64> {
        v.split('.').map(|p| p.trim().parse().unwrap_or(0)).collect()
    };
    let (x, y) = (parts(a), parts(b));
    for i in 0..x.len().max(y.len()) {
        let (p, q) = (x.get(i).copied().unwrap_or(0), y.get(i).copied().unwrap_or(0));
        if p != q {
            return p > q;
        }
    }
    false
}

/// Whether DCS still has this profile's `bfcockpit_net.dll` loaded. A loaded
/// DLL can't be opened for writing, and DCS lets go of it only when it exits.
fn dll_in_use(profile: &Path) -> bool {
    let dll = net_dll_path(profile);
    dll.is_file() && fs::OpenOptions::new().write(true).open(&dll).is_err()
}

/// One line in `<profile>\Logs\bfcockpit-update.log`, for "did it update?"
fn update_log(profile: &Path, msg: &str) {
    use std::io::Write;
    let path = profile.join("Logs").join("bfcockpit-update.log");
    if let Ok(mut f) = fs::OpenOptions::new().create(true).append(true).open(&path) {
        let secs = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_secs())
            .unwrap_or(0);
        let _ = writeln!(f, "[{secs}] {} {msg}", plugin_version());
    }
}

/// The plugin's auto-update: started hidden by the running plugin (through
/// `bfcockpit_net.dll`) with this installer freshly downloaded. It waits for
/// the player to close DCS, installs into that one profile and exits.
///
/// How often it looks: every 5 s at first -- a player who closes DCS right
/// after the update was fetched gets it straight away -- then less and less
/// often, up to once a minute, so one left waiting through a long session
/// costs next to nothing. `max_wait` bounds the whole wait; the plugin starts
/// a fresh installer next session if this one gave up.
///
/// Several can be waiting at once (an older one from an earlier session, say):
/// they take turns on a lock file, and each checks right before installing
/// that it is still newer than what is there -- so whichever order they run
/// in, the newest version is what ends up installed, never an older one.
pub fn auto_update(profile: &Path, max_wait: std::time::Duration) -> Result<String> {
    use std::{thread::sleep, time::Instant};
    let deadline = Instant::now() + max_wait;
    let mut pause = UPDATE_POLL_FIRST;
    let lock_dir = std::env::temp_dir().join("VectorStrikeCockpit");
    fs::create_dir_all(&lock_dir).ok();
    let lock_path = lock_dir.join("update.lock");
    let result = (|| -> Result<String> {
        loop {
            let installed = installed_version(profile)
                .context("the plugin isn't installed in this profile any more")?;
            if !is_newer(plugin_version(), &installed) {
                return Ok(format!("nothing to do, {installed} is installed"));
            }
            if !dll_in_use(profile) {
                // Exclusive while installing; released when it is dropped.
                #[cfg(windows)]
                let lock = {
                    use std::os::windows::fs::OpenOptionsExt;
                    fs::OpenOptions::new()
                        .create(true)
                        .write(true)
                        .share_mode(0)
                        .open(&lock_path)
                };
                #[cfg(not(windows))]
                let lock =
                    fs::OpenOptions::new().create(true).write(true).open(&lock_path);
                if let Ok(_lock) = lock {
                    let installed = installed_version(profile).unwrap_or_default();
                    if !is_newer(plugin_version(), &installed) {
                        return Ok(format!("nothing to do, {installed} is installed"));
                    }
                    match install_one(profile, DEFAULT_URL) {
                        Ok(_) => return Ok(format!("updated from {installed}")),
                        // DCS started again between the check and the write.
                        Err(e) if Instant::now() < deadline => {
                            update_log(profile, &format!("retrying: {e:#}"))
                        }
                        Err(e) => return Err(e),
                    }
                }
            }
            if Instant::now() >= deadline {
                anyhow::bail!("gave up waiting for DCS to close");
            }
            sleep(pause);
            pause = next_pause(pause);
        }
    })();
    match &result {
        Ok(msg) => update_log(profile, msg),
        Err(e) => update_log(profile, &format!("failed: {e:#}")),
    }
    result
}

const UPDATE_POLL_FIRST: std::time::Duration = std::time::Duration::from_secs(5);
const UPDATE_POLL_MAX: std::time::Duration = std::time::Duration::from_secs(60);

/// 5 s, 7.5 s, 11 s, ... up to a minute.
fn next_pause(p: std::time::Duration) -> std::time::Duration {
    (p * 3 / 2).min(UPDATE_POLL_MAX)
}

pub fn uninstall_one(profile: &Path) -> Result<Option<String>> {
    let dest = profile.join("Scripts").join("Hooks").join(HOOK_NAME);
    let dirs = [plugin_dir(profile), join_all(profile, &LEGACY_NET_DIR)];
    if !dest.is_file() && !dirs.iter().any(|d| d.is_dir()) {
        return Ok(None);
    }
    if dest.is_file() {
        fs::remove_file(&dest).with_context(|| format!("removing {}", dest.display()))?;
    }
    for dir in dirs.iter().filter(|d| d.is_dir()) {
        fs::remove_dir_all(dir).with_context(|| {
            format!(
                "removing {} -- is DCS running? Close it and try again",
                dir.display()
            )
        })?;
    }
    Ok(Some("removed".into()))
}

#[cfg(test)]
mod tests {
    use super::{api_origin, is_newer, next_pause, UPDATE_POLL_FIRST, UPDATE_POLL_MAX};

    #[test]
    fn update_poll_backs_off_to_a_minute() {
        let mut p = UPDATE_POLL_FIRST;
        let mut waited = std::time::Duration::ZERO;
        for _ in 0..12 {
            waited += p;
            p = next_pause(p);
        }
        assert_eq!(p, UPDATE_POLL_MAX);
        assert!(waited < std::time::Duration::from_secs(10 * 60), "{waited:?}");
        assert_eq!(next_pause(UPDATE_POLL_MAX), UPDATE_POLL_MAX);
    }

    #[test]
    fn versions() {
        assert!(is_newer("3.2.0", "3.1.0"));
        assert!(is_newer("3.10.0", "3.9.9"));
        assert!(is_newer("3.1.1", "3.1"));
        assert!(!is_newer("3.1.0", "3.1.0"));
        assert!(!is_newer("3.1.0", "3.2.0"));
        assert!(!is_newer("garbage", "3.1.0"));
    }

    #[test]
    fn origin() {
        assert_eq!(
            api_origin("https://api.vectorstrike.org/cockpit"),
            "https://api.vectorstrike.org"
        );
        assert_eq!(
            api_origin("http://192.168.1.50:8880/cockpit/"),
            "http://192.168.1.50:8880"
        );
        assert_eq!(
            api_origin("https://api.vectorstrike.org/"),
            "https://api.vectorstrike.org"
        );
        assert_eq!(
            api_origin("https://api.vectorstrike.org"),
            "https://api.vectorstrike.org"
        );
    }
}
